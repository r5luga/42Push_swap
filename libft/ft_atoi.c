#include "libft.h"

int	ft_atoi(const char *str)
{
	int	num;
	int	i;
	int	neg_pos;

	num = 0;
	i = 0;
	neg_pos = 1;
	while ((str[i] >= 9 && str[i] <= 13) || str[i] == 32)
	{
		i++;
	}
	if (str[i] == '+' || str[i] == '-')
	{
		if (str[i] == '-')
		{
			neg_pos = neg_pos * (-1);
		}
		i++;
	}
	while (str[i] >= '0' && str[i] <= '9')
	{
		num = num * 10 + (str[i] - '0');
		i++;
	}
	return (num * neg_pos);
}
